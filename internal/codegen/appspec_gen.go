// appspecData 是模板渲染用的内部视图（proto 生成的 message 字段均为指针，
// 此处保留指针以匹配生成的 API；模板通过 Go 模板自动解引用访问字段）。
type appspecData struct {
	Meta             *appspecv1.AppMeta
	Server           *appspecv1.ServerSpec
	Capability       *appspecv1.CapabilitySpec
	Components       []*appspecv1.ComponentSpec
	AuditBackends    []string
	BundleNormalized bool
}

func renderAppSpec(data appspecData, path string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	t := template.Must(template.New("appspec").Parse(appspecTmpl))
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return err
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// 格式化失败也落盘（便于排查模板语法），但回显原始错误。
		_ = os.WriteFile(path, buf.Bytes(), 0o644)
		return fmt.Errorf("gofmt generated main.go: %w", err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return err
	}
	fmt.Println("generated app (spec-driven):", path)
	return nil
}
