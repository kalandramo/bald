package codegen

// appspec_gen.go 是 gen app --spec 的目标目录树生成器（D2-target-codegen.md
// §2.1）：单角色 15 个落盘项（10 生成物 + 5 生成一次，随声明裁剪；
// configs/<app>.yaml 是 Gate2 派生追加项，实证见 appspec_budget_test.go 的
// 15 行清单），装配收敛到 assemble.gen.go 的唯一 Options()；生成器表达不了
// 的接线经 seeded 钩子（bootstrap/custom.go、cmd/<app>/app/custom.go）追加
// ——生成物只调用、从不覆盖（设计 §7.3 的自定义接线扩展）。
//
// 本文件没有 appspecData——模板直接吃 *appspecv1.AppSpec
// （加派生的段存在性布尔）；契约配置树整棵由 protoreflect 反射派生
// （appspec_contract.go），模板不出现任何裸配置键——加一个 bconf 段 =
// 0 处模板改动。
//
// 文件按关注点拆分：本文件是声明→视图的派生与模板渲染入口；落盘清单在
// appspec_build.go，产物模板按类别在 appspec_tmpl_app.go /
// appspec_tmpl_domain.go / appspec_tmpl_scaffold.go。

import (
	"fmt"
	"regexp"
	"strings"
	"text/template"

	appspecv1 "github.com/kalandramo/bald/bconf/gen/go/bald/appspec/v1"
	bootstrapv1 "github.com/kalandramo/bald/bconf/gen/go/bootstrap/v1"
)

// genFile 是目标目录树的一个落盘项。
type genFile struct {
	Path  string    // 相对产出根的路径
	Own   ownership // 归属三态（D2 §5.1）
	Raw   []byte    // 内容
	GoSrc bool      // .go 源码：gofmt 后落盘，gofmt 失败写 .rej 绝不触碰目标
}

// treeView 是目录树模板的共享数据：Spec 是原始声明（模板直接吃
// *appspecv1.AppSpec，无手工转写字段），其余全部为派生值——布尔来自
// 归一化契约段的反射存在性判定，字符串来自 meta/layout，没有任何
// 「proto 字段 → 模板字段」的转写层。
type treeView struct {
	Spec       *appspecv1.AppSpec
	Bootstrap  *bootstrapv1.BootstrapConfig // AppSpec.bootstrap（契约段唯一真相源）
	Module     string                       // meta.module（import 前缀）
	AppName    string                       // meta.name
	Desc       string                       // meta.desc
	APIDir     string                       // layout.apiserver_dir（默认 apiserver）
	APIPkg     string                       // <module>/internal/<apiserver_dir>
	ConfigFile string                       // configs/<app>.yaml
	HasHTTP    bool                         // 契约 server.http 段存在且非网关面
	HasGRPC    bool                         // 契约 server.grpc 段存在
	HasGateway bool                         // 契约 server.http.driver=grpc-gateway
	AnyFace    bool                         // 任一传输面存在
	Strict     bool                         // layout.strict_contract（默认 true）
	Gen        string                       // 生成命令名（头部 "Code generated by" 标识；gen app / gen domain 各自传入）
	Package    string                       // 域清单的 package 子句（bootstrapDomainsTmpl；gen domain 根级清单形态折算为 main）

	// 构建期变体（AppSpec.variants）：声明恒进计划，命中增量的实现在
	// variant_<name>.gen.go（//go:build）里注册。HasVariants 为 false 时
	// 模板不出现 variantOptions，也不落变体实现文件。
	Variants    []variantSlot
	HasVariants bool
	// HasComponents 为 true 表示需要 buildComponent：全局组件或有变体声明了
	// 组件增量（两者共用同一 kind 工厂）。
	HasComponents bool
	// Variant 是 buildTree 逐变体渲染实现文件时的当前槽位（模板只读它）。
	Variant variantSlot

	// 角色维度（meta.roles 驱动）。Roles 恒非空：roles 为空时合成一个默认
	// 角色（CmdName == AppName），让单角色生成物与引入角色前逐字节一致。
	Roles     []roleSlot // 每个角色一份派生视图
	MultiRole bool       // meta.roles 非空（模板用它选单角色/多角色分支）

	// 以下两字段由 buildTree 渲染角色文件时按角色覆写（模板只读它们）：
	CmdName  string // cmd/<cmd_name>/；单角色 == AppName
	RoleName string // 当前渲染的角色名；单角色为空串

	// RoleExpr 是 customOptions 的实参表达式（多角色 = role 变量，单角色 =
	// 空串字面量）：自定义接线钩子对两种形态同一签名，生成物只做拼装。
	RoleExpr string
}

// variantSlot 是一个变体在生成期的派生视图：When 是规范化的 Go 构建约束
// 表达式（build_tags 已按 && 连接），BuildLine 是落进实现文件头的
// //go:build 行，Detail 是人读说明；Components/Patches 是命中增量的声明面。
type variantSlot struct {
	Name       string
	When       string
	BuildLine  string
	Detail     string
	Components []*appspecv1.ComponentSpec
	Patches    []*appspecv1.VariantPatch
}

// roleSlot 是一个角色在生成期的派生视图：命名由角色名派生，传输面以
// RoleSpec.server 为准（未声明则继承 AppSpec 投影），域清单按声明序过滤。
type roleSlot struct {
	Name       string                  // meta.roles.name
	GoName     string                  // 角色名转 Go 标识（api → Api；domainOptions<GoName>）
	CmdName    string                  // <app>-<role>；单角色 == AppName
	ConfigFile string                  // configs/<app>.yaml 或 configs/<app>-<role>.yaml
	Domains    []*appspecv1.DomainSpec // 该角色承载的域（AppSpec.domains 声明序）
	HasHTTP    bool
	HasGRPC    bool
	HasGateway bool
	AnyFace    bool
}

// buildTreeView 由 AppSpec + 归一化契约段派生模板视图。
func buildTreeView(as *appspecv1.AppSpec, bs *bootstrapv1.BootstrapConfig) *treeView {
	apiDir := as.GetLayout().GetApiserverDir()
	if apiDir == "" {
		apiDir = "apiserver"
	}
	v := &treeView{
		Spec:       as,
		Bootstrap:  bs,
		Module:     as.GetMeta().GetModule(),
		AppName:    as.GetMeta().GetName(),
		Desc:       as.GetMeta().GetDesc(),
		APIDir:     apiDir,
		APIPkg:     as.GetMeta().GetModule() + "/internal/" + apiDir,
		ConfigFile: "configs/" + as.GetMeta().GetName() + ".yaml",
	}
	httpSeg := bs.GetServer().GetHttp()
	v.HasGateway = httpSeg != nil && httpSeg.GetDriver() == gatewayDriver
	v.HasHTTP = httpSeg != nil && !v.HasGateway
	v.HasGRPC = bs.GetServer().GetGrpc() != nil
	v.AnyFace = v.HasHTTP || v.HasGRPC || v.HasGateway
	// proto3 optional 保 presence：未声明 = true（D2 §3.2 LayoutSpec 默认值）。
	lc := as.GetLayout()
	v.Strict = lc == nil || lc.StrictContract == nil || lc.GetStrictContract()
	v.Gen = `"bald gen app --spec"`
	v.buildVariants(as)
	v.buildRoles(as, bs)
	// 组件工厂的落盘条件：全局组件与变体组件共用 buildComponent。
	v.HasComponents = len(v.Spec.Components) > 0
	for _, vs := range v.Variants {
		if len(vs.Components) > 0 {
			v.HasComponents = true
		}
	}
	return v
}

// buildVariants 把 AppSpec.variants 派生为模板视图：when 与 build_tags 归一
// 为唯一表达式（Gate1 已保证二者恰有一个），说明为空时给默认 Detail——诊断
// 必须能独立读懂，不能只出现一个变体名。
func (v *treeView) buildVariants(as *appspecv1.AppSpec) {
	for _, vr := range as.GetVariants() {
		when := strings.TrimSpace(vr.GetWhen())
		if when == "" {
			when = strings.Join(vr.GetBuildTags(), " && ")
		}
		detail := vr.GetDescription()
		if detail == "" {
			detail = "build-tag variant declared in AppSpec.variants (when: " + when + ")"
		}
		v.Variants = append(v.Variants, variantSlot{
			Name:       vr.GetName(),
			When:       when,
			BuildLine:  "//go:build " + when,
			Detail:     detail,
			Components: vr.GetEffects().GetComponents(),
			Patches:    vr.GetEffects().GetPatches(),
		})
	}
	v.HasVariants = len(v.Variants) > 0
}

// buildRoles 填充角色维度。roles 为空时合成一个默认角色（CmdName == AppName、
// RoleSpec 为 nil）：单角色的落盘路径、模板分支与引入角色前完全相同。
func (v *treeView) buildRoles(as *appspecv1.AppSpec, bs *bootstrapv1.BootstrapConfig) {
	roles := as.GetMeta().GetRoles()
	// 基础视图也必须带 CmdName：taskfile.yml 等共享文件用基础视图渲染，
	// 空 CmdName 会生成 `go run ./cmd/`（单角色时实测踩到过）。
	v.CmdName = v.AppName
	v.MultiRole = len(roles) > 0
	if !v.MultiRole {
		v.RoleExpr = `""`
		v.Roles = []roleSlot{{
			CmdName:    v.AppName,
			ConfigFile: v.ConfigFile,
			Domains:    as.GetDomains(),
			HasHTTP:    v.HasHTTP,
			HasGRPC:    v.HasGRPC,
			HasGateway: v.HasGateway,
			AnyFace:    v.AnyFace,
		}}
		return
	}
	v.RoleExpr = "role"
	for _, r := range roles {
		s := roleSlot{
			Name:       r.GetName(),
			GoName:     goName(r.GetName()),
			CmdName:    v.AppName + "-" + r.GetName(),
			ConfigFile: "configs/" + v.AppName + "-" + r.GetName() + ".yaml",
			Domains:    domainsOf(as, r.GetDomains()),
		}
		if srv := r.GetServer(); srv != nil {
			// 声明了 server 即以此为准：空 ServerSpec = 该角色不开任何传输面
			// （runner 的契约里因此没有 server 段，L3 段覆盖不会拦）。
			s.HasGateway = srv.GetGateway()
			s.HasHTTP = srv.GetHttp() && !s.HasGateway
			s.HasGRPC = srv.GetGrpc()
		} else {
			s.HasHTTP, s.HasGRPC, s.HasGateway = v.HasHTTP, v.HasGRPC, v.HasGateway
		}
		s.AnyFace = s.HasHTTP || s.HasGRPC || s.HasGateway
		v.Roles = append(v.Roles, s)
	}
	// 全局面 = 各角色面的并集：模板的 import 守卫与共享文件（apiserver.go
	// 只在有角色开 HTTP 面时 seed）按它判定；单角色时并集即自身，零变化。
	var anyHTTP, anyGRPC, anyGateway bool
	for _, s := range v.Roles {
		anyHTTP = anyHTTP || s.HasHTTP
		anyGRPC = anyGRPC || s.HasGRPC
		anyGateway = anyGateway || s.HasGateway
	}
	v.HasHTTP, v.HasGRPC, v.HasGateway = anyHTTP, anyGRPC, anyGateway
	v.AnyFace = anyHTTP || anyGRPC || anyGateway
}

// domainsOf 按 AppSpec.domains 的声明序取出角色引用的域（Gate1 已保证
// 引用的域存在，这里只需过滤，不重复报错）。
func domainsOf(as *appspecv1.AppSpec, names []string) []*appspecv1.DomainSpec {
	want := make(map[string]bool, len(names))
	for _, n := range names {
		want[n] = true
	}
	out := make([]*appspecv1.DomainSpec, 0, len(names))
	for _, d := range as.GetDomains() {
		if want[d.GetName()] {
			out = append(out, d)
		}
	}
	return out
}

// goName 把角色名转成 Go 标识片段（api → Api），供 domainOptions<GoName> 用。
func goName(s string) string {
	s = identRe.ReplaceAllString(s, "_")
	if s == "" {
		return "Role"
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// treeFuncs 是目录树模板的共享函数集。
var treeFuncs = template.FuncMap{
	"alias":      domainAlias, // import 路径 → Go import 别名（包基名）
	"q":          func(s string) string { return fmt.Sprintf("%q", s) },
	"title":      title,                                     // 首字母大写（域函数名派生：greet → MountGreet）
	"grpcObject": grpcObjectOf,                              // service 全名 → 授权 object（pkg/authz.DefaultGRPCObject 同源规则）
	"list":       func(ss ...string) []string { return ss }, // 模板内联字面量列表
}

// domainAlias 把域包的 import 路径折算为 Go import 别名（取包基名并清洗成
// 合法标识符；基名冲突由 Gate1 拒绝）。
func domainAlias(importPath string) string {
	base := importPath
	if i := strings.LastIndexByte(base, '/'); i >= 0 {
		base = base[i+1:]
	}
	clean := identRe.ReplaceAllString(base, "_")
	if clean == "" || clean[0] >= '0' && clean[0] <= '9' {
		clean = "_" + clean
	}
	return clean
}

var identRe = regexp.MustCompile("[^A-Za-z0-9_]")

// renderTreeTemplate 渲染目录树模板（共享 treeFuncs）。
func renderTreeTemplate(name, tmpl string, data any) ([]byte, error) {
	t, err := template.New(name).Funcs(treeFuncs).Parse(tmpl)
	if err != nil {
		return nil, err
	}
	var buf strings.Builder
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("render %s: %w", name, err)
	}
	return []byte(buf.String()), nil
}
