// ---- R1-2 审计后端热切换（逐后端 Mount/Unmount，K8s controller 语义） ----

// reconcileAudit 是期望态协调函数：配置键 audit.backends 声明「期望的审计后端
// 集合」，与实际态（rctx.Mounted()）做 diff，逐后端 Mount/Unmount——只更新变动
// 部分，失败不回滚、下次协调补齐。触发时机由框架负责：启动收敛期与配置热变更。
func reconcileAudit(ctx context.Context, rctx *appkit.ReconcileCtx) error {
	want := rctx.StringSlice("audit.backends")
	if len(want) == 0 {
		want = defaultAuditBackends // config 未设置时回退 AppSpec 声明
	}
	add, remove := appkit.DiffStrings(want, rctx.Mounted())
	if len(add) == 0 && len(remove) == 0 {
		return nil // 幂等：期望==实际，不抖动
	}

	baldlog.GetLogger().Info(ctx, "reconcile audit.backends",
		"add", strings.Join(add, ","), "remove", strings.Join(remove, ","))

	for _, name := range add {
		if err := rctx.Mount(ctx, name, &auditBackendComponent{name: name}); err != nil {
			baldlog.GetLogger().Error(ctx, "reconcile mount audit backend failed",
				"backend", name, "error", err) // 失败不回滚，下次协调补齐
		}
	}
	for _, name := range remove {
		if err := rctx.Unmount(ctx, name); err != nil {
			baldlog.GetLogger().Error(ctx, "reconcile unmount audit backend failed",
				"backend", name, "error", err)
		}
	}
	return nil
}

// auditors 记录当前生效的后端审计器（实际态）；Mount/Unmount 维护，名 == 后端名，
// 与 rctx.Mounted() 一一对应。锁仅保护 map；全局 Auditor 的重设由 applyAuditors 串行完成。
var auditors = struct {
	mu  sync.Mutex
	set map[string]audit.Auditor
}{set: make(map[string]audit.Auditor)}

// auditBackendComponent 是一个后端审计器组件：Mount 即注册进全局审计器，
// Unmount 即注销。
type auditBackendComponent struct{ name string }

func (c *auditBackendComponent) Name() string { return c.name }

func (c *auditBackendComponent) Start(ctx context.Context) error {
	a := buildAuditBackend(c.name)
	if a == nil {
		// 依赖未就绪：返回错误使挂载失败（不入实际态归属表），下次协调重试补齐。
		return fmt.Errorf("audit backend %q unavailable", c.name)
	}
	auditors.mu.Lock()
	auditors.set[c.name] = a
	auditors.mu.Unlock()
	applyAuditors()
	baldlog.GetLogger().Info(ctx, "audit backend mounted", "backend", c.name)
	return nil
}

func (c *auditBackendComponent) Dispose(ctx context.Context) error {
	auditors.mu.Lock()
	delete(auditors.set, c.name)
	auditors.mu.Unlock()
	applyAuditors()
	baldlog.GetLogger().Info(ctx, "audit backend unmounted", "backend", c.name)
	return nil
}

// buildAuditBackend 构造某后端的审计器（log 开箱即用；store/stream 依赖业务
// 的 DB/Redis 桥接，留 TODO）。返回 nil 表示依赖未就绪（挂载失败，下次重试）。
func buildAuditBackend(name string) audit.Auditor {
	switch name {
	case "log":
		return logAuditor{}
	// TODO: 接入 store/stream 后端（参考 examples/go-bald-admin 的
	// buildAuditBackend：依赖 bootstrappkg.DB / RedisCache.Client()）。
	}
	return nil
}

// applyAuditors 按后端名排序重建全局审计器（顺序确定，便于测试与排查日志）；
// 空则退化为 Nop，绝不阻断审计旁路。
func applyAuditors() {
	auditors.mu.Lock()
	names := make([]string, 0, len(auditors.set))
	for n := range auditors.set {
		names = append(names, n)
	}
	sort.Strings(names)
	list := make([]audit.Auditor, 0, len(names))
	for _, n := range names {
		list = append(list, auditors.set[n])
	}
	auditors.mu.Unlock()

	if len(list) == 0 {
		audit.SetAuditor(audit.NopAuditor())
		return
	}
	audit.SetAuditor(multiAuditor(list))
}

// logAuditor 是最小审计后端：事件落应用日志。
type logAuditor struct{}

func (logAuditor) Record(ctx context.Context, ev audit.AuditEvent) {
	baldlog.GetLogger().Info(ctx, "audit event",
		"object", ev.Object, "action", ev.Action, "result", string(ev.Result))
}

// multiAuditor 顺序广播到全部后端（核心包未提供，骨架内联最小实现）。
type multiAuditor []audit.Auditor

func (m multiAuditor) Record(ctx context.Context, ev audit.AuditEvent) {
	for _, a := range m {
		a.Record(ctx, ev)
	}
}

