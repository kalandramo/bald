// layeringTestTmpl 是 internal/<apiserver_dir>/layering_invariant_test.go
// （生成物，D2 §8.3 判据 3 的机器守卫）：随 gen app 生成进新项目，新项目
// go test ./... 即生效——biz 层不得 import 装配层。
var layeringTestTmpl = `// Code generated by {{ .Gen }}. DO NOT EDIT.
package {{ .APIDir }}

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestBizLayerImportsAreBusinessOnly 分层不变量：biz 层（业务逻辑）不得
// import 装配层（appkit / bootstrap / 注册表 / contrib contract 包）。biz 包
// 由 gen domain seed；biz 目录尚不存在时本测试跳过。
//
// 守卫是 AST 匹配而非子串匹配：go/parser 解析 import 声明块，精确到 import
// 路径字符串——注释/字符串字面量里的 "pkg/appkit" 不再误伤，import 声明
// 本身一个不漏。
func TestBizLayerImportsAreBusinessOnly(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("abs: %v", err)
	}
	bizRoot := filepath.Join(root, "internal", "{{ .APIDir }}", "biz")
	if _, err := os.Stat(bizRoot); os.IsNotExist(err) {
		t.Skip("no biz layer yet (gen domain seeds it)")
	}
	forbidden := []string{
		"pkg/appkit",         // 装配层 appkit（含 mech/std 子包）
		"internal/bootstrap", // 装配层 bootstrap
		"registry",           // 注册表包
		"contrib",            // 第三方后端 contract 包
	}
	err = filepath.WalkDir(bizRoot, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil // 显式跳过 _test.go（测试自身允许引用装配层辅助断言）
		}
		fset := token.NewFileSet()
		f, perr := parser.ParseFile(fset, path, nil, parser.ImportsOnly)
		if perr != nil {
			t.Errorf("%s: parse: %v", path, perr)
			return nil
		}
		for _, imp := range f.Imports {
			p := strings.Trim(imp.Path.Value, "\"")
			for _, rule := range forbidden {
				if strings.Contains(p, rule) {
					t.Errorf("%s imports assembly layer %q (biz must be business-only; rule %q)", path, p, rule)
				}
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk: %v", err)
	}
}
`
