package codegen

import (
	"github.com/spf13/cobra"
)

// genDomainCmd 组装 gen domain 叶子命令。
func genDomainCmd(streams ioStreams) *cobra.Command {
	o := &domainOptions{ioStreams: streams}
	cmd := &cobra.Command{
		Use:   "domain --spec <AppSpec.json>",
		Short: "按 AppSpec.domains 重写域驱动生成物（清单 + 授权投影 + 绑定）",
		Long: `消费 appspec.json 的 domains[] 与既有域 proto/域包，确定性重写域驱动生成物
（新增域触碰清单——装配改动 0）：

  - internal/bootstrap/domains.gen.go            域清单聚合（appkit.Domain 变参直传）
  - internal/<apiserver_dir>/handler/convert/<d>.gen.go 授权动作投影
  - internal/<apiserver_dir>/authz/alias.gen.go  授权别名表 + 默认动作聚合
  - <go_package>/domain.gen.go                   域声明值骨架（生成一次；域包
                                                 已有 Domain 声明时消费跳过）
  - internal/<apiserver_dir>/handler/gin/<d>.bind.gen.go  从 google.api.http
                                                 注解生成 gin 路由与服务接口
                                                 （默认生成；--no-bind 跳过）
  - internal/<apiserver_dir>/routes/<d>.gen.go   同批注解的 appkit.Route 清单
                                                 （域引用 RouteTable: routes.<Name>
                                                 即获计划可见性）；--no-routes
                                                 跳过该清单，保留手写 RouteTable

路由与 gRPC 注册的执行权在引擎（appkit.Domain.Routes / Services），本命令只
产出授权对账面与绑定实现，不再产出 apiserver 侧的挂载镜像。

Gate1 强化：domains[].service 必须与产出根下实际 proto 匹配（扫描 api/proto、
api/protos、proto），失配报错指明域、proto 文件与实际声明。全部产物 owned
（--adopt 覆盖）；域包骨架 seeded（生成一次）。--check 零写校验生成物与
清单（domains.manifest.json）是否同声明一致。

绑定生成（默认开启）：bind 文件 import proto 的 Go 类型与
bald/transport/web。两条前置由生成期校验：transport/web 缺失给出 go get 修法；
proto Go 类型缺失时先在 --out 根执行 --proto-cmd（默认 buf generate），执行
失败或仍无产物即硬错误。--check 只读，不执行外部命令，缺失时直接给出修法。
--no-bind 是显式逃生口：跳过注解派生绑定与路由清单（REST 面完全手写）。
--no-routes 与绑定生成连用：只产 bind 文件，不产路由清单（域保留手写
RouteTable）。`,
		Args:         cobra.NoArgs,
		SilenceUsage: true,
		RunE: func(*cobra.Command, []string) error {
			if err := o.Complete(); err != nil {
				return err
			}
			if err := o.Validate(); err != nil {
				return err
			}
			return o.Run()
		},
	}
	cmd.Flags().StringVar(&o.Spec, "spec", "", "AppSpec JSON 路径（protojson；必填）")
	cmd.Flags().StringVar(&o.OutDir, "out", "", "产出根（默认 .）")
	cmd.Flags().StringVar(&o.Manifest, "manifest", "", "域清单落盘路径（默认 internal/bootstrap/domains.gen.go；早期根级形态传 domains.gen.go）")
	cmd.Flags().StringVar(&o.APIServerDir, "apiserver-dir", "", "apiserver 目录名（默认 layout.apiserver_dir 否则 apiserver；传 - 跳过 apiserver 侧产物）")
	cmd.Flags().BoolVar(&o.Adopt, "adopt", false, "覆盖已存在的 owned 文件并更新清单（默认拒绝）")
	cmd.Flags().BoolVar(&o.Check, "check", false, "只校验生成物与清单是否与声明一致（零写入，有差异即失败）")
	cmd.Flags().BoolVar(&o.NoBind, "no-bind", false, "跳过 google.api.http 注解派生的 gin 绑定与路由清单（默认生成；REST 面完全手写或 proto 阶段不归本命令管时使用）")
	cmd.Flags().BoolVar(&o.RESTBind, "rest-bind", false, "（兼容保留）绑定默认生成，本开关等价于不给；关闭请用 --no-bind")
	_ = cmd.Flags().MarkDeprecated("rest-bind", "bindings are generated by default; use --no-bind to skip them")
	cmd.Flags().BoolVar(&o.NoRoutes, "no-routes", false, "绑定生成时跳过 appkit.Route 清单，域保留手写 RouteTable（生成执行、清单自持）")
	cmd.Flags().StringVar(&o.ProtoCmd, "proto-cmd", defaultProtoCmd, "绑定前置缺失时执行的 proto 生成命令（在 --out 根以 shell 语义执行）")
	_ = cmd.MarkFlagFilename("spec", ".json")
	cmd.SetErr(streams.ErrOut)
	return cmd
}
