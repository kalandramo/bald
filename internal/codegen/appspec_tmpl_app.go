// buildComponent 按 kind 构造托管组件（kind 决定工厂；生命周期由五阶段停机
// 管理，停机逆序 Dispose）。config_prefix 与 params 原样透传给组件——
// 声明面不留未消费字段。
func buildComponent(kind, name, prefix string, params map[string]string) appkit.Component {
	switch kind {
	case "heartbeat":
		return mech.ComponentFunc(name, func(ctx context.Context) error {
			// TODO: 读 prefix 下的配置（如 interval）实现真实心跳。
			baldlog.Info(ctx, "heartbeat component started", "name", name, "config_prefix", prefix, "params", params)
			return nil
		})
	default:
		// Gate1 白名单使本分支不可达（生成期已拒绝未实现 kind）；保留显式
		// 失败作为最后防线。
		panic("bootstrap: unsupported component kind " + kind)
	}
}
