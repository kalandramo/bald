// TestLayering_AST_Guard 分层守卫 AST 化的正反例（真 go test，生成物内运行）：
// 合法 import（业务 API）通过；注入装配层 import → 红，且报错指明 import 路径；
// 注释/字符串字面量里的装配层字样不误伤（AST 精确性）。
func TestLayering_AST_Guard(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go toolchain not in PATH")
	}
	dir, _ := runGenAppInTemp(t, guardFixture())
	// 正例：biz 只 import 业务 API（berrors 在任务口径的业务面）。
	writeAll(t, map[string]string{
		"internal/apiserver/biz/v1/demo/demo.go": "package demo\n\nimport \"github.com/kalandramo/bald/berrors\"\n\n// bizOnlyBusinessAPI 业务 API 引用（合法）。\nvar _ = berrors.BadRequest\n",
	})
	run := func() (string, error) {
		cmd := exec.Command("go", "test", "./internal/apiserver/", "-run", "TestBizLayerImportsAreBusinessOnly", "-count=1")
		cmd.Dir = dir
		out, err := cmd.CombinedOutput()
		return string(out), err
	}
	if out, err := run(); err != nil {
		t.Fatalf("legal biz imports must pass the AST guard: %v\n%s", err, out)
	}
	// 反例：注入装配层 import（appkit）→ 守卫必须红。
	writeAll(t, map[string]string{
		"internal/apiserver/biz/v1/bad/bad.go": "package bad\n\nimport \"github.com/kalandramo/bald/pkg/appkit\"\n\n// violation biz 引装配层（AST 守卫必须捕获）。\nvar _ = appkit.Domain{}\n",
	})
	out, err := run()
	if err == nil {
		t.Fatalf("assembly-layer import must fail the AST guard:\n%s", out)
	}
	if !strings.Contains(out, "github.com/kalandramo/bald/pkg/appkit") || !strings.Contains(out, "biz must be business-only") {
		t.Errorf("guard report must name the exact import path:\n%s", out)
	}
	// 反例不误伤：注释/字符串字面量里的装配层字样不算 import。
	writeAll(t, map[string]string{
		"internal/apiserver/biz/v1/bad/bad.go": "package bad\n\n// 见 pkg/appkit 的文档字样——仅注释，不是 import 声明。\n\nvar note = \"pkg/appkit in a string literal is not an import\"\n",
	})
	if out, err := run(); err != nil {
		t.Fatalf("comments/string literals must not trip the AST guard: %v\n%s", err, out)
	}
}

// writeAll 相对当前目录逐项落盘（测试夹具工具；t.Chdir 后的相对路径语义）。
func writeAll(t *testing.T, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		path := filepath.FromSlash(rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", path, err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
	}
}

// readRepoFile 读仓库内文件（相对 bald 仓库根）。根以本文件源码路径定位
// （runtime.Caller）——本包测试会用 t.Chdir 切走进程 cwd，repoRoot 的
// 「cwd 恒为包目录」前提在这些测试里不成立。
func readRepoFile(t *testing.T, rel string) string {
	t.Helper()
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	root := filepath.Clean(filepath.Join(filepath.Dir(thisFile), "..", ".."))
	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatalf("read repo file %s: %v", rel, err)
	}
	return string(data)
}

