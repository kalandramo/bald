// TestGenDomain_EndToEnd 参考夹具全流水线（gen app → gen domain）：产物清单
// 每文件标注 owned 通道（generated:）、清单形态对照 _example 手写件、逐域
// handler 与授权别名落在 internal/apiserver 侧、重生成确定性。
func TestGenDomain_EndToEnd(t *testing.T) {
	dir, specPath := runGenAppInTemp(t, guardFixture())
	out := runGenDomain(t, dir, specPath, "--adopt") // gen app 流水线已跑过一次 gen domain
	if got := strings.Count(out, "generated:"); got != 6 {
		t.Errorf("gen domain regen must emit 6 owned files (manifest + fanout + 3 handler + authz; domain value is seeded), got %d:\n%s", got, out)
	}

	// 域清单（internal/bootstrap）形态对照 _example 手写件：import 域包 +
	// appkit.Domain 声明值变参直传（“清单显式可 grep”）。
	manifest, err := os.ReadFile(filepath.Join(dir, "internal", "bootstrap", "domains.gen.go"))
	if err != nil {
		t.Fatalf("read manifest: %v", err)
	}
	for _, want := range []string{
		"Code generated by \"bald gen app, gen domain\". DO NOT EDIT.",
		"package bootstrap",
		"greetv1 \"demo.example/app/internal/apiserver/greetv1\"",
		"greetv1.Domain,",
		"var domainOptions = []appkit.Option{",
	} {
		if !strings.Contains(string(manifest), want) {
			t.Errorf("bootstrap manifest missing %q:\n%s", want, manifest)
		}
	}

	// apiserver 侧扇出清单：逐域 handler 挂载/注册。
	fanout, err := os.ReadFile(filepath.Join(dir, "internal", "apiserver", "domains.gen.go"))
	if err != nil {
		t.Fatalf("read apiserver manifest: %v", err)
	}
	for _, want := range []string{
		"package apiserver",
		"var DomainHandlers = []DomainHandler{",
		"Name: \"greet\", ProtoPackage: \"greet.v1\", Service: \"greet.v1.GreetService\", Model: \"internal/apiserver/model/greet.go\"",
		"Mount:    ginhandler.MountGreet",
		"Register: grpchandler.RegisterGreet",
	} {
		if !strings.Contains(string(fanout), want) {
			t.Errorf("apiserver fanout missing %q:\n%s", want, fanout)
		}
	}

	// 逐域 handler：grpc 注册委托 / gin 挂载委托 + 注解派生路由表 / convert 授权动作。
	grpcH, err := os.ReadFile(filepath.Join(dir, "internal", "apiserver", "handler", "grpc", "greet.gen.go"))
	if err != nil {
		t.Fatalf("read grpc handler: %v", err)
	}
	for _, want := range []string{"func RegisterGreet(s *grpc.Server)", "greetv1.Domain.Services(s)", "DO NOT EDIT"} {
		if !strings.Contains(string(grpcH), want) {
			t.Errorf("grpc handler missing %q:\n%s", want, grpcH)
		}
	}
	ginH, err := os.ReadFile(filepath.Join(dir, "internal", "apiserver", "handler", "gin", "greet.gen.go"))
	if err != nil {
		t.Fatalf("read gin handler: %v", err)
	}
	for _, want := range []string{
		"func MountGreet(h http.Handler) error",
		"greetv1.Domain.Routes(h)",
		"\"POST /v1/greets (body: *) -> Greet\"",
		"\"GET /v1/greets/{name} -> GreetGet\"",
	} {
		if !strings.Contains(string(ginH), want) {
			t.Errorf("gin handler missing %q:\n%s", want, ginH)
		}
	}
	convH, err := os.ReadFile(filepath.Join(dir, "internal", "apiserver", "handler", "convert", "greet.gen.go"))
	if err != nil {
		t.Fatalf("read convert handler: %v", err)
	}
	for _, want := range []string{
		"var GreetActions = map[string]string{",
		"\"greet.v1.GreetService/Greet\"",
	} {
		if !strings.Contains(string(convH), want) {
			t.Errorf("convert handler missing %q:\n%s", want, convH)
		}
	}

	// 授权别名表：gRPC 面（greet）与 HTTP 面（greets）归一化不一致 → 入表；
	// DefaultActions 经 convert 逐域聚合（编译期对账）。
	authz, err := os.ReadFile(filepath.Join(dir, "internal", "apiserver", "authz", "alias.gen.go"))
	if err != nil {
		t.Fatalf("read authz alias: %v", err)
	}
	for _, want := range []string{
		"\"greet\": \"greets\"",
		"var DefaultActions = mergeActions(convert.GreetActions)",
	} {
		if !strings.Contains(string(authz), want) {
			t.Errorf("authz alias missing %q:\n%s", want, authz)
		}
	}

	// 域声明值骨架（seeded）。
	dv, err := os.ReadFile(filepath.Join(dir, "internal", "apiserver", "greetv1", "domain.gen.go"))
	if err != nil {
		t.Fatalf("read domain value: %v", err)
	}
	for _, want := range []string{"package greetv1", "var Domain = appkit.Domain{", "Name: \"greet\","} {
		if !strings.Contains(string(dv), want) {
			t.Errorf("domain value missing %q:\n%s", want, dv)
		}
	}

	// owned 回归：无 --adopt 拒绝；--adopt 重生成字节一致（确定性）。
	dcmd := genDomainCmd(NewDefaultIOStreams())
	dcmd.SetArgs([]string{"--spec", specPath})
	if err := dcmd.Execute(); err == nil {
		t.Fatal("regen without --adopt must be refused (owned)")
	} else if !strings.Contains(err.Error(), "--adopt") {
		t.Errorf("refusal must mention --adopt, got: %v", err)
	}
	before, _ := os.ReadFile(filepath.Join(dir, "internal", "bootstrap", "domains.gen.go"))
	runGenDomain(t, dir, specPath, "--adopt")
	after, _ := os.ReadFile(filepath.Join(dir, "internal", "bootstrap", "domains.gen.go"))
	if string(before) != string(after) {
		t.Error("gen domain regeneration must be deterministic (byte-identical)")
	}
}

// TestGenDomain_ExistingDomainPackageSkipped 既有域包（_example 形态：手写
// domain.go 导出 Domain）——gen domain 消费不覆盖（skip + 不产骨架）。
func TestGenDomain_ExistingDomainPackageSkipped(t *testing.T) {
	dir := t.TempDir()
	as := guardFixture()
	specPath := writeSpecJSON(t, dir, as)
	writeFixtureProto(t, dir)
	pkgDir := filepath.Join(dir, "internal", "apiserver", "greetv1")
	if err := os.MkdirAll(pkgDir, 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	handWritten := "// Package greetv1 手写域包（既有域包——gen domain 消费不覆盖）。\npackage greetv1\n\nimport \"github.com/kalandramo/bald/pkg/appkit\"\n\n// Domain 是 greet 域的声明值（含业务接线钩子）。\nvar Domain = appkit.Domain{Name: \"greet\"}\n"
	if err := os.WriteFile(filepath.Join(pkgDir, "domain.go"), []byte(handWritten), 0o644); err != nil {
		t.Fatalf("write domain.go: %v", err)
	}
	out := runGenDomain(t, dir, specPath, "--adopt", "--manifest", "domains.gen.go", "--apiserver-dir", "-")
	if !strings.Contains(out, "skip:") || !strings.Contains(out, "(domain value already declared)") {
		t.Errorf("existing domain package must be skipped with a note, got:\n%s", out)
	}
	if _, err := os.Stat(filepath.Join(pkgDir, "domain.gen.go")); !os.IsNotExist(err) {
		t.Errorf("skeleton must not be written over an existing domain value: %v", err)
	}
	// 根级清单形态（早期 _example）：package main。
	m, err := os.ReadFile(filepath.Join(dir, "domains.gen.go"))
	if err != nil {
		t.Fatalf("read root manifest: %v", err)
	}
	if !strings.Contains(string(m), "package main") || !strings.Contains(string(m), "greetv1.Domain,") {
		t.Errorf("root-level manifest must be package main with the domain value:\n%s", m)
	}
}

