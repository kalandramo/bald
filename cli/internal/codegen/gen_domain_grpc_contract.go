package codegen

// gen_domain_grpc_contract.go 是 `gen domain` 的 gRPC 契约产物模板与
// 落盘逻辑：为每个声明了手写 gRPC service（grpc_biz_package）的域生成
// **编译期契约断言**。
//
// 与 --grpc-skeleton 的分工（两者互补，不是同一件事）：
//   - --grpc-skeleton：一次性引导（seeded，只生成一次），解决「新域从零起骨架」；
//   - --grpc-contract：常态化守卫（owned，每次重生成），解决「已有实现与 proto
//     漂移」。
//
// 为什么需要漂移守卫：handler 都嵌入 Unimplemented<T>Server
// （require_unimplemented_servers 的默认形态），于是
//   - proto 新增 RPC      → 调用落到 embed 的兜底实现，运行时 Unimplemented；
//   - proto 改动 RPC 签名 → 旧方法变成无接口约束的死方法，新签名由 embed 满足。
// 两种情况 `var _ TServer = (*impl)(nil)` 都成立——实测：只实现 5 个 RPC 中 1 个
// 的探针结构体可以编译通过。所以断言 service 接口守不住任何漂移。
//
// 本产物逐 RPC 列出**去掉兜底 embed 后**的方法集，断言真实实现结构体满足它：
// proto 增删改 RPC 后重新生成即编译失败，把「运行时 Unimplemented」提前成
// 「构建失败」。
//
// 实现约定（无法从 proto 派生，故显式约定而非猜测）：实现结构体在同目录
// （handler/grpc）、包内私有、名称为 service 短名的 lowerCamel（TenantService
// → tenantService）。与 --grpc-skeleton 生成的骨架同名，且与既有手写实现的
// 命名一致；违例时编译报 "undefined: xxxService"，错误信息自解释。

import (
	"fmt"
	"path/filepath"
	"strings"
)

// grpcContractTmpl 是 handler/grpc/<domain>.grpc_contract.gen.go（owned）。
var grpcContractTmpl = `// Code generated by "bald gen domain"; DO NOT EDIT.

package grpc

import (
	"context"
{{ range .Imports }}
	{{ if .Alias }}{{ .Alias }} {{ end }}"{{ .Path }}"
{{- end }}
)
{{- range .Services }}

// {{ .ContractName }} 是 {{ .Service }} 去掉 Unimplemented 兜底后的方法集。
//
// 为什么不直接断言 service 接口：实现结构体嵌入 Unimplemented{{ .Short }}Server
// 之后，proto 新增 RPC（调用落到兜底实现，运行时 Unimplemented）与改动签名
// （旧方法成为无人调用的死方法，新签名由 embed 满足）都不会让接口断言失败。
// 本接口只列真实 RPC，断言它才能把漂移提前成构建失败。
type {{ .ContractName }} interface {
{{- range .Methods }}
	{{ .RPC }}({{ .Params }}) {{ .Returns }}
{{- end }}
}

var _ {{ .ContractName }} = (*{{ .ImplName }})(nil)
{{- end }}
`

// grpcContractData 是一份契约文件的模板数据。
type grpcContractData struct {
	Domain   string
	Imports  []bindImport
	Services []grpcContractService
}

// grpcContractService 是一个 service 的契约视图。
type grpcContractService struct {
	Service      string // proto service 全名（<pkg>.<Name>）
	Short        string // service 短名（TenantService）
	ImplName     string // 实现结构体名（tenantService）
	ContractName string // 契约接口名（tenantServiceContract）
	Methods      []grpcContractMethod
}

// grpcContractMethod 是契约接口的一个方法（签名按流式方向派生）。
type grpcContractMethod struct {
	RPC     string // RPC 名（Go 方法名）
	Params  string // 形参列表（不含括号）
	Returns string // 返回列表（含括号）
}

// emitGRPCContracts 为声明了 grpc_biz_package 的域生成编译期契约断言文件。
//
// 方法集直接取 proto 扫描结果（不用 bindViewOf）：后者只保留带
// google.api.http 注解的 RPC，且整域零路由时返回 nil——用它当契约来源会
// 静默漏掉未注解的 RPC（如 multipart 上传/下载），恰好是漂移最容易藏身处。
func (o *domainOptions) emitGRPCContracts(v *treeView, scan *protoScan, files *[]genFile) error {
	if o.NoGRPCContract {
		return nil
	}
	byService := serviceIndex(scan)
	for _, d := range v.Spec.GetDomains() {
		if d.GetGrpcBizPackage() == "" {
			continue
		}
		names := domainServices(d)
		if len(names) == 0 {
			continue
		}
		data := grpcContractData{Domain: d.GetName()}
		addImport := func(imp bindImport) {
			if imp.Path == "" || hasImport(data.Imports, imp.Path) {
				return
			}
			data.Imports = append(data.Imports, imp)
		}
		for _, full := range names {
			svc, ok := byService[full]
			if !ok {
				return fmt.Errorf("domains (%s): service %q not found in scanned protos", d.GetName(), full)
			}
			if svc.GoPackage == "" {
				return fmt.Errorf("domain %q: proto service %q has no option go_package; the contract needs it to name request/response types", d.GetName(), full)
			}
			protoPath, alias := parseProtoGoPackage(svc.GoPackage)
			addImport(bindImport{Alias: alias, Path: protoPath})
			impl := grpcImplName(svc.Name)
			cs := grpcContractService{
				Service:      svc.Package + "." + svc.Name,
				Short:        svc.Name,
				ImplName:     impl,
				ContractName: impl + "Contract",
			}
			for _, m := range svc.Methods {
				reqExpr, reqImp := goTypeExpr(svc.Package, alias, m.Request)
				respExpr, respImp := goTypeExpr(svc.Package, alias, m.Response)
				for _, imp := range []*bindImport{reqImp, respImp} {
					if imp != nil {
						addImport(*imp)
					}
				}
				cs.Methods = append(cs.Methods, grpcContractMethod{
					RPC:     m.Name,
					Params:  grpcContractParams(alias, svc.Name, m, reqExpr),
					Returns: grpcContractReturns(respExpr, m),
				})
			}
			data.Services = append(data.Services, cs)
		}
		if len(data.Services) == 0 {
			continue
		}
		sortImports(data.Imports)
		path := filepath.Join("internal", v.APIDir, "handler", "grpc", d.GetName()+".grpc_contract.gen.go")
		raw, err := renderTreeTemplate(filepath.Base(path), grpcContractTmpl, data)
		if err != nil {
			return err
		}
		*files = append(*files, genFile{Path: path, Own: owned, Raw: raw, GoSrc: true})
	}
	return nil
}

// grpcContractParams 按流式方向派生形参列表（与 protoc-gen-go-grpc 生成的
// service 接口一致；形参名不参与接口满足性判定，只影响可读性）。
//
//	unary                  ctx context.Context, req *Req
//	server streaming       req *Req, stream <alias>.<Svc>_<RPC>Server
//	client streaming/bidi  stream <alias>.<Svc>_<RPC>Server
func grpcContractParams(alias, svc string, m protoMethod, reqExpr string) string {
	stream := "stream " + alias + "." + svc + "_" + m.Name + "Server"
	switch {
	case m.ClientStream:
		return stream
	case m.ServerStream:
		return "req *" + reqExpr + ", " + stream
	default:
		return "ctx context.Context, req *" + reqExpr
	}
}

// grpcContractReturns 按流式方向派生返回值：unary 返回 (*Resp, error)，
// 任一方向流式返回 error（响应经 stream 发送）。
func grpcContractReturns(respExpr string, m protoMethod) string {
	if m.Streaming {
		return "error"
	}
	return "(*" + respExpr + ", error)"
}

// grpcImplName 由 service 短名派生实现结构体名（TenantService → tenantService）。
//
// 首字母小写 = 包内私有实现：handler 实现不是对外 API，导出没有收益；且与
// handler/grpc 既有手写实现的命名一致（11 个实现全部符合）。--grpc-skeleton
// 与本文件共用该函数，保证两条通路产出同一名字。
func grpcImplName(short string) string {
	if short == "" {
		return "service"
	}
	return strings.ToLower(short[:1]) + short[1:]
}

// grpcServerFuncName 由 service 短名派生构造器名（TenantService → NewTenantServer）：
// 去掉冗余的 Service 后缀再拼，避免 NewTenantServiceServer。
func grpcServerFuncName(short string) string {
	base := strings.TrimSuffix(short, "Service")
	if base == "" {
		base = short
	}
	return "New" + base + "Server"
}
